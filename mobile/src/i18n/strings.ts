export function isRTL(locale: Locale): boolean {
  return locale === 'ar';
}

/**
 * Tiny interpolation helper: replaces {{key}} occurrences in a localized string
 * with the values from `vars`. Used by callers via t() returning the raw string
 * and a separate format step, or via the `format` helper exported below.
 */
export function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, k) => {
    const v = vars[k];
    return v == null ? `{{${k}}` : String(v);
  });
}
